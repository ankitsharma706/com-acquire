// Helper to get presence badge color
export function getPresenceColor(status: LivePresenceIndicator): { bg: string; text: string; border: string; label: string; dot: string } {
  switch (status) {
    case 'working':
      return {
        bg: 'bg-emerald-50 text-emerald-700',
        text: 'text-emerald-600',
        border: 'border-emerald-300',
        label: 'Working',
        dot: 'bg-emerald-500',
      };
    case 'meeting':
      return {
        bg: 'bg-blue-50 text-blue-700',
        text: 'text-blue-600',
        border: 'border-blue-300',
        label: 'In Meeting',
        dot: 'bg-blue-500',
      };
    case 'break':
      return {
        bg: 'bg-amber-50 text-amber-700',
        text: 'text-amber-600',
        border: 'border-amber-300',
        label: 'On Break',
        dot: 'bg-amber-500',
      };
    case 'offline':
      return {
        bg: 'bg-rose-50 text-rose-700',
        text: 'text-rose-600',
        border: 'border-rose-300',
        label: 'Offline',
        dot: 'bg-rose-500',
      };
    case 'reviewing':
      return {
        bg: 'bg-purple-50 text-purple-700',
        text: 'text-purple-600',
        border: 'border-purple-300',
        label: 'Reviewing Tasks',
        dot: 'bg-purple-500',
      };
    case 'lunch':
      return {
        bg: 'bg-orange-50 text-orange-700',
        text: 'text-orange-600',
        border: 'border-orange-300',
        label: 'At Lunch',
        dot: 'bg-orange-500',
      };
    case 'leave':
      return {
        bg: 'bg-slate-50 text-slate-600',
        text: 'text-slate-500',
        border: 'border-slate-300',
        label: 'On Leave',
        dot: 'bg-slate-400',
      };
    default:
      return {
        bg: 'bg-emerald-50 text-emerald-700',
        text: 'text-emerald-600',
        border: 'border-emerald-300',
        label: 'Working',
        dot: 'bg-emerald-500',
      };
  }
}
